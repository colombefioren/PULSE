namespace Pulse.Api.Infrastructure;

/// <summary>Headers every API response carries. The API only returns JSON, so its CSP allows nothing.</summary>
public sealed class SecurityHeadersMiddleware(RequestDelegate next)
{
    public Task InvokeAsync(HttpContext context)
    {
        context.Response.OnStarting(() =>
        {
            var headers = context.Response.Headers;
            headers["X-Content-Type-Options"] = "nosniff";
            headers["Referrer-Policy"] = "no-referrer";
            headers["X-Frame-Options"] = "DENY";

            // The API reference page in development loads its own scripts, so it gets no CSP.
            if (!context.Request.Path.StartsWithSegments("/scalar"))
            {
                headers["Content-Security-Policy"] = "default-src 'none'; frame-ancestors 'none'";
            }

            return Task.CompletedTask;
        });

        return next(context);
    }
}
